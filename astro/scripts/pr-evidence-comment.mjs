// Builds the PR evidence comment from a lighthouse-compare.mjs output directory:
// the desktop/mobile x light/dark screenshot table per route plus the Lighthouse
// comparison. Used by .github/workflows/pr-evidence.yml; runs locally too.
//
//   node scripts/pr-evidence-comment.mjs --out img/lighthouse/<base>-<head> \
//     --image-base https://raw.githubusercontent.com/<owner>/<repo>/<sha>/pr123/abc1234 > comment.md
//
// --image-base is where <out>/shots/*.jpg were published; pin it to a commit SHA
// so a later push can't change what an old comment shows.
import { parseArgs } from 'node:util';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export const MARKER = '<!-- pr-evidence -->';

const { values: opt } = parseArgs({
  options: {
    out: { type: 'string' },
    'image-base': { type: 'string' },
    'run-url': { type: 'string' },
    'pr-head': { type: 'string' },
    'default-routes': { type: 'string' },
  },
});
if (!opt.out) {
  console.error('usage: node scripts/pr-evidence-comment.mjs --out <lighthouse-compare dir> [--image-base url] [--run-url url] [--pr-head sha]');
  process.exit(2);
}

const summaryPath = join(opt.out, 'summary.json');
const summary = existsSync(summaryPath) ? JSON.parse(readFileSync(summaryPath, 'utf8')) : null;
const lighthouse = existsSync(join(opt.out, 'lighthouse.md')) ? readFileSync(join(opt.out, 'lighthouse.md'), 'utf8') : null;
const slug = (r) => (r === '/' ? 'home' : r.replace(/^\/+|\/+$/g, '').replace(/[^\w-]+/g, '-'));
const short = (s) => (s ?? '').slice(0, 7);

const out = [MARKER];
const head = opt['pr-head'] ?? summary?.head.sha;
out.push(`## PR evidence: \`${short(head)}\``);
const bits = ['Generated by the `pr-evidence` workflow and updated on every push'];
if (opt['run-url']) bits.push(`[run log](${opt['run-url']})`);
out.push(`_${bits.join(' · ')}. Choose pages with an \`Evidence routes: /a /b\` line in the PR description${opt['default-routes'] ? ` (default \`${opt['default-routes']}\`)` : ''}._`);

if (summary?.failures?.length) {
  out.push('', '> [!WARNING]', '> The evidence run hit errors; anything below may be partial.');
  for (const f of summary.failures) out.push(`> - ${f.split('\n')[0]}`);
}

out.push('', '### Preview screenshots');
const shots = join(opt.out, 'shots');
if (!summary) {
  out.push('', 'No results: the comparison did not run. See the run log.');
} else {
  out.push('', `PR branch (merged onto base \`${short(summary.base.sha)}\`), rendered with preview flags on.`);
  for (const route of summary.routes) {
    const cell = (device, scheme, width) => {
      const stem = `${slug(route)}-${device}-${scheme}`;
      if (!existsSync(join(shots, `${stem}.jpg`))) return '_missing_';
      if (!opt['image-base']) return `\`shots/${stem}.jpg\``;
      const full = `${opt['image-base']}/${stem}.jpg`;
      const thumb = existsSync(join(shots, `${stem}-thumb.jpg`)) ? `${opt['image-base']}/${stem}-thumb.jpg` : full;
      return `<a href="${full}"><img src="${thumb}" width="${width}" alt="${route} ${device} ${scheme}"></a>`;
    };
    out.push('', `**\`${route}\`**${summary.newRoutes?.includes(route) ? ' — new in this PR (the base has no such page)' : ''}`, '', '| | light | dark |', '|---|---|---|');
    out.push(`| **desktop 1280×800** | ${cell('desktop', 'light', 440)} | ${cell('desktop', 'dark', 440)} |`);
    out.push(`| **mobile 390×844** | ${cell('mobile', 'light', 195)} | ${cell('mobile', 'dark', 195)} |`);
  }
  out.push('', 'Thumbnails show the first screen; click one for the full page.');
}

out.push('', '### Walkthrough');
const clipsDir = join(opt.out, 'walkthrough');
const clips = existsSync(clipsDir) ? readdirSync(clipsDir).filter((f) => f.endsWith('.mp4')).sort() : [];
if (!clips.length) {
  out.push('', 'No clips: the walkthrough did not run or every route failed to load. See the run log.');
} else {
  // one row per flow; a link plays the mp4 in the browser (GitHub does not inline third-party video)
  const byFlow = new Map();
  for (const f of clips) {
    const m = f.match(/^(.*)-(desktop|mobile)-(light|dark)\.mp4$/);
    if (!m) continue;
    if (!byFlow.has(m[1])) byFlow.set(m[1], []);
    byFlow.get(m[1]).push({ file: f, label: `${m[2]} ${m[3]}` });
  }
  out.push('', 'Recorded against the PR build: a scroll-through of each evidence route, plus any `Walkthrough steps:` flow the PR names.', '', '| flow | clips |', '|---|---|');
  for (const [flow, list] of byFlow) {
    const links = list.map((c) => (opt['image-base'] ? `[${c.label}](${opt['image-base']}/${c.file})` : `\`walkthrough/${c.file}\``)).join(' · ');
    out.push(`| \`${flow}\` | ${links} |`);
  }
}

out.push('', '### Lighthouse: PR vs base', '', lighthouse ?? 'No Lighthouse results: see the run log.');

out.push('', '<details><summary>Method</summary>', '',
  '- **Builds:** base is the PR\'s base commit; head is the PR merged onto it, so only this PR\'s changes differ. Each is a production `astro build` from its own worktree, with every `preview` feature flag forced on in both.',
  '- **Frontend-only:** each tree\'s server-rendered HTML plus its own `dist/client`, served gzip-compressed with no server wait, so the numbers measure what the branch ships. Base and PR runs alternate.',
  '- **Runs:** Lighthouse CLI with simulated throttling, mobile and desktop presets. A delta is flagged only when the gap between the base and PR run ranges clears an absolute floor **and** the median moved by a relative floor (`lighthouse-verdicts.mjs`; Performance, already a 0–100 score, needs only the 3-point gap); Performance moves 10+ points between identical builds.',
  '- **⚪ No frontend change:** printed instead of deltas when base and PR serve identical HTML (ignoring Astro\'s random island ids) and identical built client files for a page.',
  '- **Walkthrough:** `astro/scripts/walkthrough.mjs` records the PR build (desktop + mobile, light) and the clips are published beside the screenshots, pinned to a commit.',
  '- **Tooling:** `astro/scripts/lighthouse-compare.mjs`, `visual-check.mjs` and `walkthrough.mjs`; see CLAUDE.md "PR evidence".',
  '', '</details>');

process.stdout.write(`${out.join('\n')}\n`);
